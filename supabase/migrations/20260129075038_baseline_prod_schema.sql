CREATE OR REPLACE FUNCTION "public"."search_terms"("search_query" "text", "result_limit" integer DEFAULT 20) RETURNS TABLE("slug" "text", "term" "text", "similarity_score" real)
    LANGUAGE "sql" STABLE
    AS $$
  select 
    t.slug,
    t.term,
    -- Calculate similarity score (1.0 for exact match, lower for partial)
    case 
      when lower(t.term) = lower(search_query) then 1.0
      when lower(t.term) like lower(search_query) || '%' then 0.9
      when lower(t.term) like '%' || lower(search_query) || '%' then 0.7
      else similarity(t.term, search_query)
    end as similarity_score
  from public.terms t
  where 
    exists (
      select 1 from public.definitions d 
      where d.term_id = t.id and d.status = 'published'
    )
    and (
      lower(t.term) like '%' || lower(search_query) || '%'
      or t.term % search_query  -- trigram similarity
    )
  order by similarity_score desc, t.term
  limit result_limit;
$$;


ALTER FUNCTION "public"."search_terms"("search_query" "text", "result_limit" integer) OWNER TO "postgres";


