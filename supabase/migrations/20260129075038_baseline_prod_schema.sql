CREATE OR REPLACE FUNCTION "public"."get_top_weighted_terms"("limit_count" integer DEFAULT 15) RETURNS TABLE("slug" "text", "term" "text")
    LANGUAGE "sql" STABLE
    AS $$
  select 
    t.slug,
    t.term
  from public.terms t
  inner join public.definitions d on d.term_id = t.id
  where d.status = 'published'
  group by t.id, t.slug, t.term
  order by max(d.weight) desc, t.term
  limit limit_count;
$$;


